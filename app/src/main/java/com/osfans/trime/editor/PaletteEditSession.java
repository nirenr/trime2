package com.osfans.trime.editor;

import java.io.IOException;
import java.io.StringReader;
import org.luaj.Globals;
import org.luaj.LuaValue;
import org.luaj.Prototype;

/** Worker-confined compilation cache. Each replay still uses a fresh Lua environment. */
final class PaletteEditSession {
    interface Factory { Globals create(); }
    static final class Result {
        final String patch;
        final Globals model; // null means an unchanged property/patch; retain the existing UI.
        Result(String patch,Globals model){this.patch=patch;this.model=model;}
    }
    private static final int MAX_CACHE_CHARS=512*1024;
    private final Factory factory;
    private final Chunk baseChunk=new Chunk(),patchChunk=new Chunk();
    PaletteEditSession(Factory factory){this.factory=factory;}

    private static final class Chunk {
        String source;
        Prototype prototype;
        LuaValue load(Globals g,String text,String name)throws IOException {
            // This LuaJ fork resolves wildcard Java imports while compiling. Do not
            // cache such scripts or retain unusually large source/prototype pairs.
            if(text.length()>MAX_CACHE_CHARS||text.contains("import")){
                source=null;prototype=null;return g.load(text,name,g);
            }
            if(prototype==null||!text.equals(source)){
                Prototype compiled=g.compilePrototype(new StringReader(text),name);
                source=text;prototype=compiled;
            }
            // Only bytecode/constants are shared. Closures, tables, environments and
            // upvalues are fresh on every execution.
            return g.loader.load(prototype,name,g,g);
        }
    }
    private Globals base(String source)throws IOException {
        Globals g=factory.create();baseChunk.load(g,source,"editor").call();return g;
    }
    private void apply(Globals g,String source,String patch)throws IOException {
        LuaPatchManager.verifyBase(source,patch);
        if(!patch.trim().isEmpty())patchChunk.load(g,patch,"@editor.custom.lua").call(g);
    }
    Globals evaluate(String source,String patch)throws IOException {
        Globals g=base(source);apply(g,source,patch);return g;
    }
    /** literal is a scalar Lua literal generated by the editor, never arbitrary input code. */
    Result edit(String source,String previous,String path,String literal,boolean detach)throws IOException {
        Globals g=base(source);
        LuaPatchManager.Snapshot before=new LuaPatchManager.Snapshot(g);
        apply(g,source,previous);
        PaletteResolver resolver=new PaletteResolver(g);
        // A matching inherited value is NOT a no-op: applying it may create an
        // explicit override. Also never skip an intentional detach or deletion.
        if(!detach&&!literal.equals("nil")){
            LuaValue raw=resolver.rawPath(path);
            if(!raw.isnil()&&(raw.isboolean()||raw.type()==LuaValue.TNUMBER||raw.type()==LuaValue.TSTRING)){
                LuaValue desired=g.load("return "+literal,"editor scalar").call();
                if(raw.type()==desired.type()&&raw.raweq(desired))return new Result(previous,null);
            }
        }
        g.load(PaletteProperties.assignment(path,literal,detach,resolver),"editor change").call();
        String next=LuaPatchManager.bindToBase(source,before.delta());
        if(next.equals(previous))return new Result(previous,null);
        // Keep canonical replay validation even for dynamic Lua, rather than publish
        // an edited environment that may not match the serialized sidecar.
        return new Result(next,evaluate(source,next));
    }
    /** Ordered list edits use the same compile cache and canonical patch replay. */
    Result editButtons(String source,String previous,String path,StyleButtonLists.Edit edit)throws IOException {
        Globals g=base(source);LuaPatchManager.Snapshot before=new LuaPatchManager.Snapshot(g);apply(g,source,previous);
        StyleButtonLists.apply(g,path,edit);
        String next=LuaPatchManager.bindToBase(source,before.delta());
        return next.equals(previous)?new Result(previous,null):new Result(next,evaluate(source,next));
    }

}
